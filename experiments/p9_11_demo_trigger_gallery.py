"""P9.11: image files for the dashboard's trigger gallery, from the PUBLIC DEMO KEY only.

    python experiments/p9_11_demo_trigger_gallery.py

CPU, seconds. Regenerates P1.3's demo trigger set with the repo's own trigger
code (`src.watermark.triggers.generate_triggers`) and P1.3's public demo key,
and refuses to write anything unless the regenerated images hash to the
``trigger_images_sha256`` that P1.3 recorded. So the gallery shows exactly the
committed P1.3 demo set, nothing new is measured, and the owner key `K` is
never read.

For the first `GALLERY_SIZE` triggers it writes three PNGs each under
``figures/p9.11_demo_triggers/``: the clean base image, the trigger, and the
applied perturbation stretched from [-A, A] to [0, 255] (P1.3's mapping), all
upscaled `UPSCALE` times with nearest-neighbour so the pixels stay visible.
The PNGs carry no metadata, so a rerun writes identical bytes.

The record lists each file with its SHA-256 and the base image's class. The
dashboard reads the record and the PNGs through its manifest-checked data
layer.
"""

from __future__ import annotations

import glob
import hashlib
import io
import time
from pathlib import Path

import _bootstrap  # noqa: F401  -- puts the repo root on sys.path

import numpy as np
from PIL import Image

from p1_3_visualize_triggers import DEMO_KEY, DEMO_KEY_PHRASE, UPSCALE, _stretch
from src.data.cifar10 import CLASS_NAMES, cifar10_split_indices
from src.utils.results import git_info, read_result, repo_root, write_result
from src.utils.seeding import DEFAULT_SEED
from src.watermark.triggers import DEFAULT_AMPLITUDE, DEFAULT_N, generate_triggers

GALLERY_SIZE = 12
OUT_DIR = "figures/p9.11_demo_triggers"
PANELS = ("base", "trigger", "perturbation")


def png_bytes(image: np.ndarray) -> bytes:
    big = image.repeat(UPSCALE, axis=0).repeat(UPSCALE, axis=1)
    buffer = io.BytesIO()
    Image.fromarray(big, mode="RGB").save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def main() -> dict:
    git, started = git_info(), time.perf_counter()
    p1_3_path = sorted(glob.glob(str(repo_root() / "results" / "p1.3_trigger_visualization__*.json")))[-1]
    p1_3 = read_result(p1_3_path)
    if p1_3["params"]["demo_key_sha256_hex"] != DEMO_KEY.hex():
        raise SystemExit("P1.3's recorded demo key differs from the demo key in its script")

    from torchvision.datasets import CIFAR10

    cifar = CIFAR10(str(repo_root() / "data"), train=True, download=False)
    pool, _ = cifar10_split_indices(len(cifar.data))
    triggers = generate_triggers(DEMO_KEY, cifar.data, pool, n=DEFAULT_N, amplitude=DEFAULT_AMPLITUDE)
    digest = hashlib.sha256(triggers.images.tobytes()).hexdigest()
    if digest != p1_3["metrics"]["trigger_images_sha256"]:
        raise SystemExit(f"regenerated demo triggers hash to {digest}, P1.3 recorded "
                         f"{p1_3['metrics']['trigger_images_sha256']}; refusing to write")
    labels = np.asarray(cifar.targets)[triggers.base_indices]

    out = repo_root() / OUT_DIR
    out.mkdir(parents=True, exist_ok=True)
    items = []
    for i in range(GALLERY_SIZE):
        panels = {"base": triggers.base_images[i], "trigger": triggers.images[i], "perturbation": _stretch(triggers, i)}
        files = {}
        for name in PANELS:
            data = png_bytes(panels[name])
            path = out / f"trigger_{i:02d}_{name}.png"
            path.write_bytes(data)
            files[name] = {"path": f"{OUT_DIR}/{path.name}", "sha256": hashlib.sha256(data).hexdigest()}
        items.append({"index": i, "base_class": CLASS_NAMES[int(labels[i])], "files": files})

    path = write_result(
        "p9.11_demo_trigger_gallery", DEFAULT_SEED, task="P9.11", git=git,
        duration_seconds=time.perf_counter() - started,
        params={"key": "PUBLIC DEMO KEY = sha256(DEMO_KEY_PHRASE), not an owner key",
                "demo_key_phrase": DEMO_KEY_PHRASE.decode(), "demo_key_sha256_hex": DEMO_KEY.hex(),
                "trigger_code": "src/watermark/triggers.py generate_triggers", "n": DEFAULT_N,
                "amplitude": DEFAULT_AMPLITUDE, "gallery_size": GALLERY_SIZE, "upscale": UPSCALE,
                "perturbation_display": "applied perturbation mapped from [-A, A] to [0, 255] (P1.3 _stretch)",
                "p1_3_record": Path(p1_3_path).relative_to(repo_root()).as_posix()},
        metrics={"trigger_images_sha256": digest, "matches_p1_3": True, "items": items},
        notes="Demo-key triggers only, regenerated byte-identical to the committed P1.3 set; no owner key read; "
              "nothing measured.")
    print(f"wrote {GALLERY_SIZE} x {len(PANELS)} PNGs under {OUT_DIR} and {path}")
    return {"path": str(path), "items": items}


if __name__ == "__main__":
    main()
